#[cfg(test)]
mod tests {
    use super::event_name;

    #[test]
    fn known_ids_have_names_and_new_ones_do_not() {
        assert_eq!(event_name(224), Some("pattern notes"));
        assert_eq!(event_name(199), Some("version"));
        assert_eq!(event_name(250), None);
        assert_eq!(event_name(63), None);
    }
}
